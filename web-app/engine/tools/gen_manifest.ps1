# Writes engine\BACKEND_MANIFEST.txt (SHA-256 of every backend file the engine compiles or includes) and
# engine\src\BackendManifest.generated.h (aggregate hash used by sys.hello). Backend files are only read.
$ErrorActionPreference = 'Stop'
$engine = Split-Path -Parent $PSScriptRoot
$repo   = (Resolve-Path (Join-Path $engine '..\..')).Path

$exclude = @{
  'console-app\src'     = '^(ConsoleView|main)\.cpp$'
  'console-app\include' = '^ConsoleView\.h$'
  'desktop-app\src'     = '^(Gui.*|Page.*|Theme|gui_main)\.cpp$'
  'desktop-app\include' = '^(Gui.*|Page.*|Pages|Theme|resource)\.h$'
}
$lines = New-Object System.Collections.Generic.List[string]
foreach ($rel in @('console-app\src','console-app\include','desktop-app\src','desktop-app\include')) {
  $dir = Join-Path $repo $rel
  Get-ChildItem -LiteralPath $dir -File | Where-Object { $_.Name -match ".(cpp|h)$" -and $_.Name -notmatch $exclude[$rel] } |
    Sort-Object { $_.Name } | ForEach-Object {
      $relSlash = $rel.Replace([string][char]92, '/')
      $h = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLower()
      $lines.Add(('{0}  {1}/{2}' -f $h, $relSlash, $_.Name))
    }
}
$body = ($lines -join "`n") + "`n"
$bytes = [System.Text.Encoding]::UTF8.GetBytes($body)
$sha = [System.Security.Cryptography.SHA256]::Create()
$agg = ([System.BitConverter]::ToString($sha.ComputeHash($bytes)) -replace '-','').ToLower()

$header = "# Backend files compiled into cb_engine (SHA-256, LF line endings). Generated by engine/tools/gen_manifest.ps1`n" +
          "# Files: $($lines.Count)   Aggregate SHA-256 of the lines below: $agg`n" + $body
[System.IO.File]::WriteAllText((Join-Path $engine 'BACKEND_MANIFEST.txt'), $header, (New-Object System.Text.UTF8Encoding($false)))

$h = "// generated by engine/tools/gen_manifest.ps1: do not edit`n#define CB_BACKEND_MANIFEST_SHA256 `"$agg`"`n#define CB_BACKEND_MANIFEST_FILES $($lines.Count)`n"
[System.IO.File]::WriteAllText((Join-Path $engine 'src\BackendManifest.generated.h'), $h, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "manifest: $($lines.Count) files, aggregate $agg"
